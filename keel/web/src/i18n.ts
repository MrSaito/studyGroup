export type Strings = typeof en;

const loaders: Record<Exclude<Locale, "en">, () => Promise<{ default: Partial<Strings> }>> = {
  ur: () => import("./locales/ur.ts"),
  ar: () => import("./locales/ar.ts"),
  zh: () => import("./locales/zh.ts"),
  ru: () => import("./locales/ru.ts"),
  es: () => import("./locales/es.ts"),
};
const cache: Partial<Record<Locale, Strings>> = { en };

/** Resolves the full table for a locale (English fills any gap). Cached after first load. */
export async function loadStrings(locale: Locale): Promise<Strings> {
  const hit = cache[locale];
  if (hit) return hit;
  const m = await loaders[locale as Exclude<Locale, "en">]();
  const table: Strings = { ...en, ...m.default };
  cache[locale] = table;
  return table;
}
export function isLocale(x: unknown): x is Locale { return typeof x === "string" && LOCALES.some((l) => l.code === x); }
